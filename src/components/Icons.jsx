/**
 * APL Electric Company sunburst emblem.
 * Blue disc with a sharp golden sunburst — matches the official APL logo mark.
 * The star polygon is generated so the spikes stay crisp and evenly spaced.
 */
export const IconAplSunburst = ({ className = "w-10 h-10" }) => {
  const CX = 150;
  const CY = 150;
  const OUTER = 146;
  const INNER = 100;
  const SPIKES = 30;

  const points = [];
  for (let i = 0; i < SPIKES * 2; i += 1) {
    const radius = i % 2 === 0 ? OUTER : INNER;
    const angle = (Math.PI * i) / SPIKES - Math.PI / 2;
    const x = (CX + radius * Math.cos(angle)).toFixed(2);
    const y = (CY + radius * Math.sin(angle)).toFixed(2);
    points.push(`${x},${y}`);
  }

  return (
    <svg
      className={className}
      viewBox="0 0 300 300"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
    >
      {/* Blue outer disc */}
      <circle cx="150" cy="150" r="150" fill="#0072CE" />
      {/* Golden spiky sunburst */}
      <polygon points={points.join(' ')} fill="#F5B800" />
    </svg>
  );
};


--  TABLE LAYOUT (what you asked for)
--
--      ID        Meter No        KCT1        KCT2
--      --------  --------------  ----------  ----------
--      1         450198231102    1234567890  0987654321
--
--    ID       auto-generated primary key
--    Meter No the customer's meter number (spaces/dashes are stripped on save,
--             so "4501 9823-1102" and "450198231102" are the SAME customer)
--    KCT1     key change token 1 (TID rollover token — first to load)
--    KCT2     key change token 2 (TID rollover token — load after KCT1)
--
--  WHAT IT CREATES
--    Table    : tid_meters        — one row per customer meter
--    Storage  : a public "tid-meter-records" bucket of <meter>.json files
--    Security : the public site may READ a meter (to generate its TID token),
--               but only a signed-in admin may WRITE records.
--
--  The front-end reads through `src/lib/meterApi.js`: it first queries the
--  tid_meters table, then falls back to <meter>.json in the storage bucket.
-- ============================================================================

create extension if not exists pgcrypto;

-- ============================================================================
--  1. TID METERS — ID | Meter No | KCT1 | KCT2
-- ============================================================================
create table if not exists public.tid_meters (
    id          bigint      generated by default as identity primary key,
    meter_no    text        not null unique,   -- normalised: digits only
    kct1        text,                          -- key change token 1
    kct2        text,                          -- key change token 2
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

comment on table public.tid_meters is
    'TID rollover register: ID, Meter No, KCT1, KCT2. Look up a meter by `meter_no` to return its key change tokens.';
comment on column public.tid_meters.meter_no is
    'Meter number with all spaces/dashes removed, so lookups are formatting-tolerant.';
comment on column public.tid_meters.kct1 is 'Key change token 1 — load this on the meter first.';
comment on column public.tid_meters.kct2 is 'Key change token 2 — load this on the meter after KCT1.';

create index if not exists tid_meters_meter_no_idx
    on public.tid_meters (meter_no);

-- Normalise Meter No on every insert/update so the lookup never has to guess.
create or replace function public.normalize_meter_no()
returns trigger
language plpgsql
as $$
begin
  new.meter_no = upper(regexp_replace(coalesce(new.meter_no, ''), '[^0-9A-Za-z]', '', 'g'));
  return new;
end;
$$;

drop trigger if exists tid_meters_normalize on public.tid_meters;
create trigger tid_meters_normalize
    before insert or update on public.tid_meters
    for each row execute function public.normalize_meter_no();

-- ------------------------------------------------------------- updated_at --
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists tid_meters_touch on public.tid_meters;
create trigger tid_meters_touch
    before update on public.tid_meters
    for each row execute function public.touch_updated_at();

-- ============================================================================
--  2. ROW LEVEL SECURITY
-- ============================================================================
alter table public.tid_meters enable row level security;

grant usage on schema public to anon, authenticated;
grant select                 on public.tid_meters to anon, authenticated;
grant insert, update, delete on public.tid_meters to authenticated;

-- Anyone may look up a meter to generate its TID token...
drop policy if exists "tid meters are readable by everyone" on public.tid_meters;
create policy "tid meters are readable by everyone"
    on public.tid_meters for select
    to anon, authenticated
    using (true);

-- ...but only a signed-in admin may add, edit or remove records.
drop policy if exists "tid meters are writable by admins" on public.tid_meters;
create policy "tid meters are writable by admins"
    on public.tid_meters for all
    to authenticated
    using (true) with check (true);

-- ============================================================================
--  3. STORAGE — public "tid-meter-records" bucket of <meter>.json files
-- ============================================================================
insert into storage.buckets (id, name, public)
values ('tid-meter-records', 'tid-meter-records', true)
on conflict (id) do update set public = true;

-- Anyone may read a meter record (used to render the TID token)...
drop policy if exists "tid meter records are publicly readable" on storage.objects;
create policy "tid meter records are publicly readable"
    on storage.objects for select
    to anon, authenticated
    using (bucket_id = 'tid-meter-records');

-- ...but only a signed-in admin may upload, replace or remove files.
drop policy if exists "tid meter records are uploaded by admins" on storage.objects;
create policy "tid meter records are uploaded by admins"
    on storage.objects for insert
    to authenticated
    with check (bucket_id = 'tid-meter-records');

drop policy if exists "tid meter records are updated by admins" on storage.objects;
create policy "tid meter records are updated by admins"
    on storage.objects for update
    to authenticated
    using (bucket_id = 'tid-meter-records')
    with check (bucket_id = 'tid-meter-records');

drop policy if exists "tid meter records are removed by admins" on storage.objects;
create policy "tid meter records are removed by admins"
    on storage.objects for delete
    to authenticated
    using (bucket_id = 'tid-meter-records');

